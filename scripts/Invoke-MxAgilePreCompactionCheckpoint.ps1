<#
.SYNOPSIS
    Executes the MxAgile Pre-Compaction Protocol before context compaction.

.DESCRIPTION
    Implements the 17-step pre-compaction protocol defined in
    .mxagile/policies/context-transition.md.

    Must complete successfully before any compaction is allowed to proceed.
    On validation failure: does NOT report success, does NOT advance transition
    state, preserves prior valid checkpoint, blocks safely.

    Designed to be called from:
      - Claude Code PreCompact hook
      - MxAgile transition coordinator before programmatic compaction request
      - Manual pre-compaction checkpoint

    Does NOT trigger compaction itself.
    Does NOT advance the transition state machine beyond CHECKPOINT_VALIDATED.

.PARAMETER ProjectRoot
    Absolute path to the project root.

.PARAMETER TransitionRequestId
    Stable idempotency ID for this transition. Generated by caller if not supplied.
    Persisted in checkpoint before submission.

.PARAMETER HotContextSummary
    1-3 sentence HOT context summary for the new epoch.

.PARAMETER NextAction
    Next safe action description after compaction/resume.

.PARAMETER NextActionSafe
    True if the next action can start without additional confirmation.

.PARAMETER NextChecklistItem
    Specific checklist item to resume from (e.g. W01-03).

.PARAMETER SkipContextModeExternalization
    Skip optional Context Mode WARM externalization even if available.

.OUTPUTS
    PSCustomObject with:
      .Success                — boolean
      .TransitionState        — CHECKPOINT_VALIDATED | CHECKPOINT_PREPARING | TRANSITION_BLOCKED
      .TransitionRequestId    — string (generated or supplied)
      .CheckpointPath         — string (operational checkpoint path)
      .HandoffPath            — string (handoff copy path or empty)
      .ValidationPassed       — boolean
      .BlockingReasons        — string[]
      .PreCompactionTime      — ISO datetime
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)]
    [string]$ProjectRoot,

    [string]$TransitionRequestId = "",

    [string]$HotContextSummary = "",

    [string]$NextAction = "Re-sync and continue mission after compaction",

    [bool]$NextActionSafe = $false,

    [string]$NextChecklistItem = "",

    [switch]$SkipContextModeExternalization
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$ProjectRoot = [System.IO.Path]::GetFullPath($ProjectRoot)
$now = Get-Date -Format 'yyyy-MM-ddTHH:mm:ss'

$blocking = [System.Collections.Generic.List[string]]::new()

# ---------------------------------------------------------------------------
# Step 1-2: Identify active mission and context epoch
# ---------------------------------------------------------------------------
$readerScript = Join-Path $PSScriptRoot "Read-MxAgileEpochCheckpoint.ps1"
if (-not (Test-Path -LiteralPath $readerScript)) {
    return [PSCustomObject]@{
        Success             = $false
        TransitionState     = "TRANSITION_BLOCKED"
        TransitionRequestId = $TransitionRequestId
        CheckpointPath      = ""
        HandoffPath         = ""
        ValidationPassed    = $false
        BlockingReasons     = @("checkpoint_reader_missing")
        PreCompactionTime   = $now
    }
}

$currentCheckpoint = & $readerScript -ProjectRoot $ProjectRoot

if (-not $currentCheckpoint.Valid) {
    $blocking.Add("no_valid_checkpoint: $($currentCheckpoint.ConflictReason)")
    return [PSCustomObject]@{
        Success             = $false
        TransitionState     = "CHECKPOINT_PREPARING"
        TransitionRequestId = $TransitionRequestId
        CheckpointPath      = ""
        HandoffPath         = ""
        ValidationPassed    = $false
        BlockingReasons     = [string[]]$blocking.ToArray()
        PreCompactionTime   = $now
    }
}

# Guard: terminal missions do not proceed
if ($currentCheckpoint.MissionStatus -eq "complete" -or $currentCheckpoint.MissionStatus -eq "failed") {
    $blocking.Add("mission_terminal: $($currentCheckpoint.MissionStatus)")
    return [PSCustomObject]@{
        Success             = $false
        TransitionState     = "TRANSITION_BLOCKED"
        TransitionRequestId = $TransitionRequestId
        CheckpointPath      = ""
        HandoffPath         = ""
        ValidationPassed    = $false
        BlockingReasons     = [string[]]$blocking.ToArray()
        PreCompactionTime   = $now
    }
}

# ---------------------------------------------------------------------------
# Step 3: Repository reality inspection
# ---------------------------------------------------------------------------
$_savedEap = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
$gitBranch = & git -C $ProjectRoot rev-parse --abbrev-ref HEAD 2>$null
$gitCommit = & git -C $ProjectRoot rev-parse --short HEAD 2>$null
$gitStatus = & git -C $ProjectRoot status --porcelain 2>$null
$ErrorActionPreference = $_savedEap

$workingTreeState = "unknown"
if ($LASTEXITCODE -eq 0) {
    $workingTreeState = if ([bool]$gitStatus) { "dirty" } else { "clean" }
}

# ---------------------------------------------------------------------------
# Step 4-14: Generate transition request ID if not supplied
# ---------------------------------------------------------------------------
if ([string]::IsNullOrEmpty($TransitionRequestId)) {
    # Generate stable ID based on epoch + timestamp
    $epochId = $currentCheckpoint.EpochId
    $TransitionRequestId = "TXN-$epochId-$(Get-Date -Format 'yyyyMMddHHmmss')"
}

# ---------------------------------------------------------------------------
# Step 15: Optional Context Mode WARM externalization
# ---------------------------------------------------------------------------
# Context Mode is optional and must not block compaction if unavailable.
# Actual externalization requires Context Mode to be enabled and available.
# This step is advisory only.
$contextModeSkipped = $SkipContextModeExternalization.IsPresent

# ---------------------------------------------------------------------------
# Steps 4-14 + 16: Write pre-compaction checkpoint with transition metadata
# ---------------------------------------------------------------------------
$writerScript = Join-Path $PSScriptRoot "Write-MxAgileEpochCheckpoint.ps1"
if (-not (Test-Path -LiteralPath $writerScript)) {
    $blocking.Add("checkpoint_writer_missing")
    return [PSCustomObject]@{
        Success             = $false
        TransitionState     = "TRANSITION_BLOCKED"
        TransitionRequestId = $TransitionRequestId
        CheckpointPath      = ""
        HandoffPath         = ""
        ValidationPassed    = $false
        BlockingReasons     = [string[]]$blocking.ToArray()
        PreCompactionTime   = $now
    }
}

# Write the pre-compaction checkpoint
& $writerScript `
    -ProjectRoot $ProjectRoot `
    -MissionId $currentCheckpoint.MissionId `
    -MissionObjective $currentCheckpoint.MissionObjective `
    -MissionStatus $currentCheckpoint.MissionStatus `
    -CurrentPhase $currentCheckpoint.CurrentPhase `
    -EpochId $currentCheckpoint.EpochId `
    -RolloverReason "auto_rollover" `
    -NextAction $NextAction `
    -NextActionSafe $NextActionSafe `
    -NextChecklistItem $NextChecklistItem `
    -HotContextSummary $HotContextSummary `
    -PreserveEvidence `
    -WriteHandoffCopy

# ---------------------------------------------------------------------------
# Step 16: Validate the pre-compaction checkpoint
# ---------------------------------------------------------------------------
$validatedCheckpoint = & $readerScript -ProjectRoot $ProjectRoot

if (-not $validatedCheckpoint.Valid) {
    $blocking.Add("pre_compaction_checkpoint_invalid: $($validatedCheckpoint.ConflictReason)")
    return [PSCustomObject]@{
        Success             = $false
        TransitionState     = "TRANSITION_BLOCKED"
        TransitionRequestId = $TransitionRequestId
        CheckpointPath      = ""
        HandoffPath         = ""
        ValidationPassed    = $false
        BlockingReasons     = [string[]]$blocking.ToArray()
        PreCompactionTime   = $now
    }
}

# ---------------------------------------------------------------------------
# Step 17: Persist transition request identity in operational checkpoint
# ---------------------------------------------------------------------------
$concordDir  = Join-Path $ProjectRoot ".concord"
$cpPath      = Join-Path $concordDir "context-epoch.yaml"
$handoffDir  = Join-Path $ProjectRoot "planning\lifecycle"
$handoffPath = Join-Path $handoffDir "context-epoch.yaml"

# Append transition metadata to checkpoint
if (Test-Path -LiteralPath $cpPath) {
    $cpContent = Get-Content -LiteralPath $cpPath -Raw -Encoding UTF8

    # Add transition_state and transition_request_id if not already present
    if ($cpContent -notmatch 'transition_state:') {
        $transitionBlock = @"

  # Context Transition metadata (added by pre-compaction protocol)
  transition_state: CHECKPOINT_VALIDATED
  transition_request_id: "$TransitionRequestId"
  pre_compaction_checkpoint_valid: true
  post_compaction_resync_required: false
  compaction_summary_received: false
"@
        $cpContent = $cpContent.TrimEnd() + $transitionBlock + "`n"
        $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
        [System.IO.File]::WriteAllText($cpPath, $cpContent, $utf8NoBom)

        if (Test-Path -LiteralPath $handoffPath) {
            [System.IO.File]::WriteAllText($handoffPath, $cpContent, $utf8NoBom)
        }
    }
}

$handoffResult = if (Test-Path -LiteralPath $handoffPath) { $handoffPath } else { "" }

Write-Host "Pre-compaction checkpoint validated: $($validatedCheckpoint.EpochId)" -ForegroundColor Green
Write-Host "Transition request ID: $TransitionRequestId" -ForegroundColor Cyan
Write-Host "Checkpoint: $cpPath" -ForegroundColor Cyan
if ($contextModeSkipped) {
    Write-Host "Context Mode externalization: skipped" -ForegroundColor Gray
}

return [PSCustomObject]@{
    Success             = $true
    TransitionState     = "CHECKPOINT_VALIDATED"
    TransitionRequestId = $TransitionRequestId
    CheckpointPath      = $cpPath
    HandoffPath         = $handoffResult
    ValidationPassed    = $true
    BlockingReasons     = @()
    PreCompactionTime   = $now
}

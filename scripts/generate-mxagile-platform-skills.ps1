Generate-GrokSkills

Write-Host "`n--- OpenCode ---"
Generate-OpenCodeSkills

Write-Host "`n--- Hermes ---"
Generate-HermesSkills

Write-Host "`n--- Directory Skills ---"
Generate-BundledSkills

$python = Get-Command python -ErrorAction SilentlyContinue
if (-not $python) { $python = Get-Command python3 -ErrorAction SilentlyContinue }
if (-not $python) { throw 'PROJECTION_PREFLIGHT_UNAVAILABLE: Python is required for ownership validation.' }
$ioScript = Join-Path $PSScriptRoot 'projection_io.py'
if (-not (Test-Path -LiteralPath $ioScript -PathType Leaf)) { throw "Projection I/O helper missing: $ioScript" }
$request = @{ project_root = $ProjectRoot; core_commit = $CoreCommit; core_version = $CoreVersion; apply = -not ($DryRun -or $PreflightOnly); outputs = @($projectionOutputs); ownership_baseline = @($OwnershipBaseline); expected_plan_fingerprint = $ExpectedPlanFingerprint }
$PSNativeCommandUseErrorActionPreference = $false
$OutputEncoding = [Text.UTF8Encoding]::new($false)
$raw = ($request | ConvertTo-Json -Depth 12 -Compress) | & $python.Source -B $ioScript
$code = $LASTEXITCODE
$report = ($raw -join "`n") | ConvertFrom-Json
if ($code -ne 0 -or -not $report.ready) {
    Write-Host ($report | ConvertTo-Json -Depth 12 -Compress)
    $failure=[InvalidOperationException]::new("SKILL_PROJECTION_CONFLICT: projection preflight/apply failed; exit=$code")
    $failure.Data['projection_report']=$report
    throw $failure
}
foreach ($output in $projectionOutputs) { Write-Host "  $(if ($request.apply) { 'Generated' } else { '[PREFLIGHT]' }): $($output.target)" }
Write-Host "PROJECTION_STATUS: $($report.stage) outputs=$($report.output_count)"
if ($PassThru) { $report }
Write-Host "`nDone."

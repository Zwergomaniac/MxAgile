<#
.SYNOPSIS
    Generates platform-specific skills and agents from .mxagile/ neutral sources.

.DESCRIPTION
    Reads neutral skill/agent bodies from .mxagile/skills/ and .mxagile/agents/,
    prepends platform-specific frontmatter, and writes the result into platform
    directories (.claude/, .github/, .agents/, .grok/, .opencode/, .hermes/).

    All generated files carry a "# GENERATED" header and the mxagile- prefix.
    Adapter YAML files under .mxagile/adapters/ document the frontmatter per
    platform but are not parsed at runtime — the configuration is inline below.

    Directory naming for non-Claude/Copilot platforms uses "mxagile/" (not "dfc/").

.PARAMETER ProjectRoot
    Root directory of the Mendix project. Defaults to current directory.

.PARAMETER DryRun
    Show what would be generated without writing files.
#>
[CmdletBinding()]
param(
    [string]$ProjectRoot = $PWD.Path,
    [string]$CoreCommit  = "",
    [string]$CoreVersion = "",
    [string]$SourceRoot = "",
    [string]$BundledSkillRoot = "",
    [switch]$PreflightOnly,
    [object[]]$OwnershipBaseline = @(),
    [string]$ExpectedPlanFingerprint = "",
    [switch]$PassThru,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$ProjectRoot = [IO.Path]::GetFullPath($ProjectRoot)
$mxagileRoot = if ($SourceRoot) { [IO.Path]::GetFullPath($SourceRoot) } else { Join-Path $ProjectRoot '.mxagile' }
$projectionOutputs = [Collections.Generic.List[object]]::new()
$generatedHeader = "# GENERATED - DO NOT EDIT - Source: .mxagile/`n# WARNING: This file is automatically generated by generate-mxagile-platform-skills.ps1.`n# Manual changes will be overwritten."

if (-not (Test-Path $mxagileRoot)) {
    Write-Error ".mxagile/ directory not found at $mxagileRoot"
    exit 1
}

function Get-FirstContentLine {
    param([string]$Body)
    foreach ($line in ($Body -split '\n')) {
        $trimmed = $line.Trim()
        if ($trimmed -and -not $trimmed.StartsWith('#')) {
            return $trimmed
        }
    }
    return "MxAgile process skill"
}

function Get-ProjectionRelativePath {
    param([string]$Base, [string]$Path)
    $baseUri=[Uri]([IO.Path]::GetFullPath($Base).TrimEnd('\','/') + [IO.Path]::DirectorySeparatorChar)
    $pathUri=[Uri][IO.Path]::GetFullPath($Path)
    return [Uri]::UnescapeDataString($baseUri.MakeRelativeUri($pathUri).ToString()).Replace('\','/')
}

function Add-ProjectionOutput {
    param([string]$OutputPath, [byte[]]$Bytes, [string]$SourceFile, [string]$OwnerRoot)
    $target = Get-ProjectionRelativePath -Base $ProjectRoot -Path $OutputPath
    if (-not $OwnerRoot) {
        $parent = Split-Path $OutputPath -Parent
        $OwnerRoot = if ((Split-Path $OutputPath -Leaf) -eq 'SKILL.md' -or (Split-Path $parent -Leaf) -eq 'mxagile') { $parent } else { $OutputPath }
    }
    $relativeSource = Get-ProjectionRelativePath -Base $mxagileRoot -Path $SourceFile
    if ($relativeSource.StartsWith('../')) {
        if (-not $BundledSkillRoot) { throw "Projection source escapes canonical roots: $SourceFile" }
        $relativeSource = 'skills/' + (Get-ProjectionRelativePath -Base $BundledSkillRoot -Path $SourceFile)
        if ($relativeSource -match '(^|/)\.\.(/|$)') { throw "Invalid bundled source: $SourceFile" }
    }
    $projectionOutputs.Add(@{ target = $target; owner_root = (Get-ProjectionRelativePath -Base $ProjectRoot -Path $OwnerRoot); source = '.mxagile/' + $relativeSource; data = [Convert]::ToBase64String($Bytes) })
}

function Write-Generated {
    param([string]$OutputPath, [string]$Content, [string]$SourceFile)
    Add-ProjectionOutput -OutputPath $OutputPath -Bytes ([Text.UTF8Encoding]::new($false).GetBytes($Content)) -SourceFile $SourceFile
}

function Get-BundledSkill {
    param([string]$SkillFile)
    $content = Get-Content -LiteralPath $SkillFile -Raw -Encoding UTF8
    $match = [regex]::Match($content, '(?s)\A---\r?\n(?<fields>.*?)\r?\n---\r?\n')
    if (-not $match.Success) {
        throw "Bundled skill is missing YAML frontmatter: $SkillFile"
    }

    $fields = @{}
    foreach ($line in ($match.Groups['fields'].Value -split '\r?\n')) {
        if ($line -notmatch '^(?<key>name|description):\s*(?<value>.*)$') {
            throw "Bundled skill frontmatter only permits name and description: $SkillFile"
        }
        $key = $Matches['key']
        if ($fields.ContainsKey($key)) { throw "Duplicate bundled skill field '$key': $SkillFile" }
        $fields[$key] = $Matches['value'].Trim()
    }
    if ((@($fields.Keys | Sort-Object) -join ',') -ne 'description,name') {
        throw "Bundled skill must contain exactly name and description: $SkillFile"
    }
    if ($fields['name'] -cnotmatch '^[a-z0-9]+(?:-[a-z0-9]+)*$' -or $fields['name'] -match '(^|-)skill($|-)') {
        throw "Invalid bundled skill name '$($fields['name'])': $SkillFile"
    }
    if (-not $fields['description'] -or $fields['description'] -cne $fields['description'].ToLowerInvariant()) {
        throw "Bundled skill description must be non-empty and lowercase: $SkillFile"
    }

    return [pscustomobject]@{
        Name = $fields['name']
        Content = $content
        FrontmatterLength = $match.Length
    }
}

function Write-GeneratedBundledSkill {
    param([string]$OutputPath, [string]$Content, [string]$SourceFile)
    Write-Generated -OutputPath $OutputPath -Content $Content -SourceFile $SourceFile
}

function Generate-BundledSkills {
    $skillsDir = Join-Path $mxagileRoot 'skills'
    $skillFiles = @{}
    foreach ($skillFile in (Get-ChildItem -LiteralPath $skillsDir -Filter 'SKILL.md' -File -Recurse)) {
        $skillFiles[$skillFile.Directory.Name] = $skillFile.FullName
    }

    if ($BundledSkillRoot) {
        foreach ($skillFile in (Get-ChildItem -LiteralPath $BundledSkillRoot -Filter 'SKILL.md' -File -Recurse -Force)) {
            $skillFiles[$skillFile.Directory.Name] = $skillFile.FullName
        }
    }
    foreach ($skillName in @($skillFiles.Keys | Sort-Object)) {
        $skillFilePath = $skillFiles[$skillName]
        $skillFile = Get-Item -LiteralPath $skillFilePath
        $skill = Get-BundledSkill -SkillFile $skillFile.FullName
        if ($skill.Name -cne $skillFile.Directory.Name) { throw "Skill source directory/name mismatch: $($skillFile.FullName)" }
        $body = $skill.Content.Substring($skill.FrontmatterLength)
        $frontmatter = $skill.Content.Substring(0, $skill.FrontmatterLength).TrimEnd()
        $generatedContent = "$frontmatter`n$generatedHeader`n$body"
        $outputs = @(
            (Join-Path $ProjectRoot ".claude/skills/$($skill.Name)/SKILL.md"),
            (Join-Path $ProjectRoot ".github/skills/$($skill.Name)/SKILL.md"),
            (Join-Path $ProjectRoot ".agents/skills/$($skill.Name)/SKILL.md")
        )
        foreach ($outputPath in $outputs) {
            Write-GeneratedBundledSkill -OutputPath $outputPath -Content $generatedContent -SourceFile $skillFile.FullName
            foreach ($resourceKind in @('assets', 'references')) {
                $resourceRoot = Join-Path $skillFile.Directory.FullName $resourceKind
                if (-not (Test-Path -LiteralPath $resourceRoot -PathType Container)) { continue }
                foreach ($resource in (Get-ChildItem -LiteralPath $resourceRoot -Recurse -File -Force)) {
                    if ($resource.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Invalid projection source reparse point: $($resource.FullName)" }
                    $relativePath = $resource.FullName.Substring($skillFile.Directory.FullName.Length).TrimStart('\', '/')
                    $destination = Join-Path (Split-Path -Parent $outputPath) $relativePath
                    Add-ProjectionOutput -OutputPath $destination -Bytes ([IO.File]::ReadAllBytes($resource.FullName)) -SourceFile $resource.FullName -OwnerRoot (Split-Path -Parent $outputPath)
                }
            }
        }
    }
}


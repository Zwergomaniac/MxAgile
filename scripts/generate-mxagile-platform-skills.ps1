# --- Main ---
$python = Get-Command python -ErrorAction Stop
$sourceRoots = @($mxagileRoot)
if ($BundledSkillRoot) { $sourceRoots += $BundledSkillRoot }
$PSNativeCommandUseErrorActionPreference = $false
& $python.Source -B -c 'import sys; sys.path.insert(0,sys.argv[1]); from projection_io import validate_sources; validate_sources(sys.argv[2:])' $PSScriptRoot @sourceRoots
if ($LASTEXITCODE -ne 0) { throw 'PROJECTION_INPUT_INVALID: canonical sources contain invalid files, schemas or reparse points.' }
Write-Host "MxAgile Platform Skill Generator"
Write-Host "================================"
Write-Host "Source: $mxagileRoot"
Write-Host ""

Write-Host "--- Claude ---"
Generate-ClaudeSkills
Generate-ClaudeAgents

Write-Host "`n--- Copilot ---"
Generate-CopilotSkills

Write-Host "`n--- Codex ---"
Generate-CodexSkills

